// What is a singly linked list?
// It is a data structure consisting of nodes where each node contains a value and a reference to the next node in the sequence.
// The last node points to null, indicating the end of the list.

// We can't take direct access to an element by its index like we can in an array.

// Complexities of common operations in a singly linked list:
// Access by index: O(n)
// Search by value: O(n)

// Insertion at the beginning: O(1)
// Insertion at the end: O(1)
// Insertion at an arbitrary index: O(n)

// Deletion at the beginning: O(1)
// Deletion at the end: O(n)
// Deletion at an arbitrary index: O(n)