// TREE - hierarchical data structure consisting of nodes, with a single node called the root, and zero or more child nodes for each node.
// Trees are used to represent hierarchical relationships

// DIFFERENCE BETWEEN TREE AND LINKED LIST:
// – A linked list is a linear data structure
// – A tree is a not linear hierarchical data structure with a root node and child nodes

// WHERE IT'S USED:
// – HTML DOM
// – in file systems to represent directory structures
// – in artificial intelligence for decision trees
// - in network routing

// RULES:
// 1. Only one root
// 2. Link to child nodes, but not so siblings directly.
// 3. Node cannot be its own ancestor or descendant.

// TERMINOLOGY:
// – Root: The topmost node of the tree.
// – Parent: A node that has one or more child nodes.
// – Child: A node that has a parent node.
// – Sibling: Nodes that share the same parent.
// – Leaf: A node with no children.
// - Edge: The connection between a parent node and a child node.